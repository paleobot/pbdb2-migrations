CREATE TABLE taxa (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permid integer NOT NULL,
    authorizer_person_id integer REFERENCES persons("id") NOT NULL, -- Whoever was the authorizer of the enterer
    enterer_person_id integer REFERENCES persons("id") NOT NULL, -- Whoever made the entry or edit
    name text NOT NULL, -- see special consideration below
    authority_id integer NOT NULL, -- the authority
    assignment_id integer REFERENCES assignment_opinions("id"), -- the "best" opinion for the parent taxon (e.g., family of genus)
    synonym_id integer REFERENCES synonymy_opinions("id"), -- the "best" opinion for SENIOR synonym (e.g., Brachiosaurus -> Giraffatitan)
    nomenclature_id integer REFERENCES nomenclature_opinions("id") NOT NULL, -- the "best" opinion for name/spelling
    description_id integer REFERENCES descriptions("id"), -- the "best" description. I am leaving this table undescribed for now because it touches on the PBOT system
    validity_id integer REFERENCES validity_opinions("id") NOT NULL, -- the "best" opinion on validity (nome nudem etc.)
    has_homonym boolean NOT NULL, -- see table notes below
    preceded_by_id integer REFERENCES taxa("id"),
    succeeded_by_id integer REFERENCES taxa("id")
    );

-- This is for table for opinions changing the taxonomic placement (e.g., family of genus) for a taxon
