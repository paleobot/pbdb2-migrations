-- Lookup table for homonyms. Homonyms are treated differently because their existence is not necessarily derived from an 
-- opinion, but from a practical reality in our database. Furthermore, it is theoretically possible (though I know of no examples) 
-- for there to be more than two taxa sharing the same name, so a simple one-to-one child->parent style table structure like in -- the synonymy opinions tables would not work.
CREATE TABLE homonyms (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    younger_taxon_A_id integer REFERENCES taxa("id"), -- taxon with younger authority
    older_taxon_B_id integer REFERENCES taxa("id") -- taxon with older authority
    );

-- The most significant change here is that we essentially eliminate reidentification as a separate table
-- Instead, if something is a reidentification of a previous iteration, we link back to that prior occurrence

-- Also see the above change to the taxa table and the remove of orig_no
CREATE TABLE occurrences {
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permid text NOT NULL,
    authorizer_person_id integer REFERENCES persons("id") NOT NULL, -- Whoever was the authorizer of the enterer
    enterer_person_id integer REFERENCES persons("id") NOT NULL, -- Whoever made the entry or edit
    taxon_id integer REFERENCES taxa("id") NOT NULL, -- the taxon in question
    reidentification_occurrence_id integer REFERENCES occurrences("id"),
    collection_id integer REFERENCES collections("id") NOT NULL, -- collection taxon belongs to
    reference_id integer REFERENCES references("id") NOT NULL,
    preceded_by_id integer REFERENCES occurrences("id"),
    succeeded_by_id integer REFERENCES occurrences("id")
    };

