// Build a throwaway REFERENCE database and populate its opinion tables by running
// the 48 hand-written migration_exploration/opinions/ handlers against it — an
// independent oracle for cross-checking the single-script migrate-opinions.js
// output (see cross-check-reference.js).
//
// The reference DB (PG_REF_DATABASE, default 'pbdb_ref') is created as a TEMPLATE
// clone of the primary PG_DATABASE, so it inherits the IDENTICAL dictionaries and
// root name_opinions (hence identical permids) — which lets the cross-check compare
// output rows directly on permids with no translation. Its opinion OUTPUTS are then
// cleared (roots kept) and regenerated by the 48 handlers, which read the same
// MariaDB source as migrate-opinions.js (real db.js, MIGRATION_TEST_MODE unset).
//
// Usage:
//   node run-reference-handlers.js          build + clear + run all 48 handlers
//   node run-reference-handlers.js --drop    drop the reference DB (teardown)
//
// The reference DB is a ~1x clone of the primary DB; drop it when the cross-check
// is done (space). This script is the single place that creates and drops it.
import 'dotenv/config';
import { Pool } from 'pg';
import { spawn } from 'node:child_process';
import { readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const OPINIONS_DIR = join(REPO_ROOT, 'migration_exploration', 'opinions');
const PRIMARY_DB = process.env.PG_DATABASE;
const REF_DB = process.env.PG_REF_DATABASE || 'pbdb_ref';

if (!/^[a-zA-Z0-9_]+$/.test(REF_DB)) throw new Error(`unsafe PG_REF_DATABASE: ${REF_DB}`);

function maintenancePool() {
  // Connect to the 'postgres' maintenance DB (CREATE/DROP DATABASE can't run
  // inside the target DB or a transaction).
  return new Pool({
    host: process.env.PG_HOST, port: parseInt(process.env.PG_PORT || '5432', 10),
    user: process.env.PG_USER, password: process.env.PG_PASSWORD, database: 'postgres', max: 1,
  });
}

function refPool() {
  return new Pool({
    host: process.env.PG_HOST, port: parseInt(process.env.PG_PORT || '5432', 10),
    user: process.env.PG_USER, password: process.env.PG_PASSWORD, database: REF_DB, max: 1,
  });
}

async function dropRefDb() {
  const admin = maintenancePool();
  try {
    await admin.query(`SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE datname = $1 AND pid <> pg_backend_pid()`, [REF_DB]);
    await admin.query(`DROP DATABASE IF EXISTS ${REF_DB}`);
    console.log(`  Dropped ${REF_DB}.`);
  } finally { await admin.end(); }
}

async function createRefDb() {
  const admin = maintenancePool();
  try {
    await admin.query(`SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE datname = $1 AND pid <> pg_backend_pid()`, [REF_DB]);
    await admin.query(`DROP DATABASE IF EXISTS ${REF_DB}`);
    // TEMPLATE clone requires no other sessions on the source DB.
    await admin.query(`SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE datname = $1 AND pid <> pg_backend_pid()`, [PRIMARY_DB]);
    console.log(`  Cloning ${PRIMARY_DB} → ${REF_DB} (TEMPLATE)...`);
    await admin.query(`CREATE DATABASE ${REF_DB} TEMPLATE ${PRIMARY_DB}`);
    console.log('  Clone complete.');
  } finally { await admin.end(); }
}

async function clearOutputs() {
  // TRUNCATE (metadata-only, no per-row FK checks) rather than DELETE: the cloned
  // opinion tables carry unindexed self-referential FKs (preceded_by_id /
  // succeeded_by_id), which make a full DELETE O(n²) and effectively hang. Roots
  // must survive, so they're captured and re-inserted around a TRUNCATE ... CASCADE
  // of all three opinion tables.
  const ref = refPool();
  try {
    await ref.query('BEGIN');
    await ref.query(`CREATE TEMP TABLE _roots ON COMMIT DROP AS SELECT * FROM name_opinions WHERE edge_class='root'`);
    await ref.query(`TRUNCATE assignment_opinions, validity_opinions, name_opinions CASCADE`);
    await ref.query(`INSERT INTO name_opinions SELECT * FROM _roots`);
    await ref.query('COMMIT');
    // Re-inserting explicit root ids does not advance the identity sequences; set
    // them past the max so handler inserts (identity-generated) don't collide.
    await ref.query(`SELECT setval(pg_get_serial_sequence('assignment_opinions','id'), GREATEST((SELECT COALESCE(MAX(id),1) FROM assignment_opinions),1))`);
    await ref.query(`SELECT setval(pg_get_serial_sequence('validity_opinions','id'), GREATEST((SELECT COALESCE(MAX(id),1) FROM validity_opinions),1))`);
    await ref.query(`SELECT setval(pg_get_serial_sequence('name_opinions','id'), GREATEST((SELECT COALESCE(MAX(id),1) FROM name_opinions),1))`);
    const { rows } = await ref.query(`SELECT COUNT(*)::int n FROM name_opinions WHERE edge_class='root'`);
    console.log(`  Cleared outputs; ${rows[0].n} root name_opinions retained.`);
  } catch (e) {
    await ref.query('ROLLBACK').catch(() => {});
    throw e;
  } finally { await ref.end(); }
}

function handlerFiles() {
  const files = [];
  for (const folder of readdirSync(OPINIONS_DIR, { withFileTypes: true })) {
    if (!folder.isDirectory()) continue;
    for (const f of readdirSync(join(OPINIONS_DIR, folder.name))) {
      if (f.endsWith('.js')) files.push(join(OPINIONS_DIR, folder.name, f));
    }
  }
  return files.sort();
}

function runHandler(path) {
  return new Promise((resolve) => {
    // PG_DATABASE=REF_DB is passed explicitly; dotenv (loaded inside the handler's
    // pools) does NOT override already-set env vars, so the handler writes to REF_DB.
    // MIGRATION_TEST_MODE is unset → real MariaDB source + real pg target.
    const env = { ...process.env, PG_DATABASE: REF_DB };
    delete env.MIGRATION_TEST_MODE;
    const child = spawn(process.execPath, [path], { cwd: REPO_ROOT, stdio: 'inherit', env });
    child.on('exit', (code) => resolve(code));
  });
}

async function main() {
  if (process.argv.includes('--drop')) {
    console.log(`[${new Date().toISOString()}] Dropping reference DB ${REF_DB}...`);
    await dropRefDb();
    return;
  }

  console.log(`[${new Date().toISOString()}] Building reference DB ${REF_DB} (clone of ${PRIMARY_DB})...`);
  await createRefDb();
  await clearOutputs();

  const files = handlerFiles();
  console.log(`[${new Date().toISOString()}] Running ${files.length} handlers against ${REF_DB}...`);
  for (let i = 0; i < files.length; i++) {
    console.log(`\n--- [${i + 1}/${files.length}] ${files[i].replace(REPO_ROOT + '/', '')} ---`);
    const code = await runHandler(files[i]);
    if (code !== 0) {
      console.error(`STOPPED: handler exited ${code}. ${REF_DB} left for inspection.`);
      process.exitCode = 1;
      return;
    }
  }

  const ref = refPool();
  try {
    const { rows } = await ref.query(`
      SELECT 'assignment_opinions' t, COUNT(*) n FROM assignment_opinions
      UNION ALL SELECT 'validity_opinions', COUNT(*) FROM validity_opinions
      UNION ALL SELECT 'name_opinions concept', COUNT(*) FROM name_opinions WHERE edge_class='concept'
      UNION ALL SELECT 'name_opinions lineage', COUNT(*) FROM name_opinions WHERE edge_class='lineage'`);
    console.log(`\n[${new Date().toISOString()}] All ${files.length} handlers done. Reference counts:`);
    for (const r of rows) console.log(`    ${r.t}: ${r.n}`);
  } finally { await ref.end(); }
  console.log(`\nNext: node src/opinions-migration/cross-check-reference.js`);
  console.log(`Then teardown: node src/opinions-migration/run-reference-handlers.js --drop`);
}

main().catch((err) => { console.error('run-reference-handlers failed:', err.message); process.exitCode = 1; });
